-- 16. Using RANK(), rank plans by total revenue (monthly_price x active count).
SELECT p.plan_id,
       p.plan_name,
       p.monthly_price,
       COUNT(*) AS active_subs,
       p.monthly_price * COUNT(*) AS total_revenue,
       RANK() OVER (ORDER BY p.monthly_price * COUNT(*) DESC) AS revenue_rank
FROM subscriptions s
JOIN subscription_plans p USING (plan_id)
WHERE subscription_status = 'Active'
GROUP BY p.plan_id, p.plan_name, p.monthly_price
ORDER BY revenue_rank;

-- 17. Using ROW_NUMBER(), identify each customer's most recent support ticket.
WITH ranked AS (
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY customer_id
                              ORDER BY ticket_date DESC, ticket_id DESC) AS rn
    FROM support_tickets
)
SELECT ticket_id, customer_id, ticket_date, issue_category, ticket_status
FROM ranked
WHERE rn = 1;

-- 18. 3-month moving average of new customer registrations (window function).
WITH monthly AS (
    SELECT DATE_TRUNC('month', registration_date)::date AS month,
           COUNT(*) AS new_customers
    FROM customers
    GROUP BY 1
)
SELECT month,
       new_customers,
       ROUND(AVG(new_customers) OVER (ORDER BY month
              ROWS BETWEEN 2 PRECEDING AND CURRENT ROW), 2) AS moving_avg_3m
FROM monthly
ORDER BY month;

-- 19. Using LAG(), customers whose most recent month watch time < prior month.
WITH monthly_watch AS (
    SELECT customer_id,
           DATE_TRUNC('month', viewing_date)::date AS month,
           SUM(watch_duration_minutes) AS watch_minutes
    FROM viewing_activity
    GROUP BY 1, 2
),
with_lag AS (
    SELECT *,
           LAG(watch_minutes) OVER (PARTITION BY customer_id ORDER BY month) AS prev_minutes
    FROM monthly_watch
)
SELECT customer_id, month, watch_minutes, prev_minutes
FROM with_lag
WHERE prev_minutes IS NOT NULL AND watch_minutes < prev_minutes;

-- 20. Cohort retention: % of each registration-month cohort still active at 1, 3, 6 months.
WITH cohorts AS (
    SELECT customer_id,
           DATE_TRUNC('month', registration_date)::date AS cohort_month
    FROM customers
),
subs AS (
    SELECT customer_id,
           subscription_start_date,
           COALESCE(subscription_end_date, '9999-12-31'::date) AS end_date
    FROM subscriptions
)
SELECT c.cohort_month,
       COUNT(DISTINCT c.customer_id) AS cohort_size,
       ROUND(100.0 * COUNT(DISTINCT CASE WHEN EXISTS (
               SELECT 1 FROM subs s
               WHERE s.customer_id = c.customer_id
                 AND s.subscription_start_date <= c.cohort_month + INTERVAL '1 month'
                 AND s.end_date > c.cohort_month + INTERVAL '1 month')
             THEN c.customer_id END) / COUNT(DISTINCT c.customer_id), 1) AS retained_1m,
       ROUND(100.0 * COUNT(DISTINCT CASE WHEN EXISTS (
               SELECT 1 FROM subs s
               WHERE s.customer_id = c.customer_id
                 AND s.subscription_start_date <= c.cohort_month + INTERVAL '3 months'
                 AND s.end_date > c.cohort_month + INTERVAL '3 months')
             THEN c.customer_id END) / COUNT(DISTINCT c.customer_id), 1) AS retained_3m,
       ROUND(100.0 * COUNT(DISTINCT CASE WHEN EXISTS (
               SELECT 1 FROM subs s
               WHERE s.customer_id = c.customer_id
                 AND s.subscription_start_date <= c.cohort_month + INTERVAL '6 months'
                 AND s.end_date > c.cohort_month + INTERVAL '6 months')
             THEN c.customer_id END) / COUNT(DISTINCT c.customer_id), 1) AS retained_6m
FROM cohorts c
GROUP BY c.cohort_month
ORDER BY c.cohort_month;

-- 21. Using DENSE_RANK(), top 5 countries by churn rate.
WITH churn AS (
    SELECT c.country,
           COUNT(*) AS customers,
           SUM(cl.churned::int) AS churned
    FROM customers c
    LEFT JOIN churn_labels cl ON cl.customer_id = c.customer_id
    GROUP BY c.country
),
ranked AS (
    SELECT country,
           customers,
           churned,
           ROUND(100.0 * churned / customers, 2) AS churn_rate_pct,
           DENSE_RANK() OVER (ORDER BY 100.0 * churned / customers DESC) AS rnk
    FROM churn
)
SELECT country, customers, churned, churn_rate_pct
FROM ranked
WHERE rnk <= 5
ORDER BY rnk;

