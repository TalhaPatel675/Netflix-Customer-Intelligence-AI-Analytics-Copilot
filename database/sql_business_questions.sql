-- 28. Customers with 2+ failed payments in last 90 days flagged as high churn risk.
WITH failed AS (
    SELECT customer_id,
           COUNT(*) AS failed_payment_count
    FROM payments
    WHERE payment_status = 'Failed'
      AND payment_date >= CURRENT_DATE - INTERVAL '90 days'
    GROUP BY customer_id
    HAVING COUNT(*) >= 2
),
risk AS (
    SELECT customer_id FROM churn_labels WHERE churned = TRUE
)
SELECT f.customer_id,
       f.failed_payment_count,
       s.plan_id AS current_plan
FROM failed f
JOIN risk r ON r.customer_id = f.customer_id
JOIN subscriptions s ON s.customer_id = f.customer_id AND s.subscription_status = 'Active'
ORDER BY f.failed_payment_count DESC;

-- 29. Engagement 30 days before vs after each customer's most recent price change.
WITH price_changes AS (
    SELECT customer_id,
           subscription_start_date AS change_date,
           monthly_price AS new_price,
           LAG(monthly_price) OVER (PARTITION BY customer_id
                                    ORDER BY subscription_start_date) AS old_price
    FROM subscriptions
),
changes AS (
    SELECT customer_id, change_date
    FROM price_changes
    WHERE old_price IS NOT NULL AND new_price <> old_price
)
SELECT ch.customer_id,
       ROUND(AVG(CASE WHEN e.viewing_date BETWEEN ch.change_date - INTERVAL '30 days' AND ch.change_date
                      THEN e.watch_duration_minutes END), 2) AS avg_before,
       ROUND(AVG(CASE WHEN e.viewing_date > ch.change_date
                      AND e.viewing_date <= ch.change_date + INTERVAL '30 days'
                      THEN e.watch_duration_minutes END), 2) AS avg_after,
       ROUND(100.0 * (AVG(CASE WHEN e.viewing_date > ch.change_date
                               AND e.viewing_date <= ch.change_date + INTERVAL '30 days'
                               THEN e.watch_duration_minutes END)
                     - AVG(CASE WHEN e.viewing_date BETWEEN ch.change_date - INTERVAL '30 days' AND ch.change_date
                                 THEN e.watch_duration_minutes END))
             / NULLIF(AVG(CASE WHEN e.viewing_date BETWEEN ch.change_date - INTERVAL '30 days' AND ch.change_date
                               THEN e.watch_duration_minutes END), 0), 2) AS pct_change
FROM changes ch
JOIN viewing_activity e ON e.customer_id = ch.customer_id
GROUP BY ch.customer_id
HAVING AVG(CASE WHEN e.viewing_date BETWEEN ch.change_date - INTERVAL '30 days' AND ch.change_date
                THEN e.watch_duration_minutes END) IS NOT NULL
   AND AVG(CASE WHEN e.viewing_date > ch.change_date
                AND e.viewing_date <= ch.change_date + INTERVAL '30 days'
                THEN e.watch_duration_minutes END) IS NOT NULL;

-- 30. Per-country summary: total, churned, churn rate, avg CLV (churned), top reason.
WITH country_stats AS (
    SELECT c.country,
           COUNT(DISTINCT c.customer_id) AS total_customers,
           COUNT(DISTINCT CASE WHEN cl.churned THEN c.customer_id END) AS churned_customers,
           ROUND(100.0 * COUNT(DISTINCT CASE WHEN cl.churned THEN c.customer_id END)
                 / NULLIF(COUNT(DISTINCT c.customer_id), 0), 2) AS churn_rate_pct
    FROM customers c
    LEFT JOIN churn_labels cl ON cl.customer_id = c.customer_id
    GROUP BY c.country
),
clv AS (
    SELECT c.country,
           AVG(p.amt) AS avg_clv_churned
    FROM customers c
    JOIN churn_labels cl ON cl.customer_id = c.customer_id AND cl.churned
    LEFT JOIN (SELECT customer_id, SUM(amount) AS amt
               FROM payments WHERE payment_status = 'Success' GROUP BY customer_id) p
           ON p.customer_id = c.customer_id
    GROUP BY c.country
),
top_reason AS (
    SELECT c.country,
           cl.churn_reason,
           COUNT(*) AS n,
           ROW_NUMBER() OVER (PARTITION BY c.country ORDER BY COUNT(*) DESC) AS rn
    FROM customers c
    JOIN churn_labels cl ON cl.customer_id = c.customer_id
       AND cl.churned AND cl.churn_reason IS NOT NULL
    GROUP BY c.country, cl.churn_reason
)
SELECT cs.country,
       cs.total_customers,
       cs.churned_customers,
       cs.churn_rate_pct,
       ROUND(clv.avg_clv_churned, 2) AS avg_clv_churned,
       tr.churn_reason AS top_churn_reason
FROM country_stats cs
LEFT JOIN clv ON clv.country = cs.country
LEFT JOIN top_reason tr ON tr.country = cs.country AND tr.rn = 1
ORDER BY cs.churn_rate_pct DESC;

-- 31. At-risk revenue report: composite SQL risk score x monthly_price, top 50.
WITH recency AS (
    SELECT customer_id,
           (CURRENT_DATE - MAX(viewing_date)) AS days_since_last_activity
    FROM viewing_activity
    GROUP BY customer_id
),
failed AS (
    SELECT customer_id,
           COUNT(*) FILTER (WHERE payment_status = 'Failed') AS failed_count,
           COUNT(*) AS total_count
    FROM payments
    GROUP BY customer_id
),
tickets AS (
    SELECT customer_id, COUNT(*) AS ticket_count
    FROM support_tickets
    GROUP BY customer_id
),
active AS (
    SELECT customer_id, plan_id, monthly_price
    FROM subscriptions
    WHERE subscription_status = 'Active'
)
SELECT a.customer_id,
       a.plan_id,
       a.monthly_price,
       COALESCE(r.days_since_last_activity, 365) AS days_since_last_activity,
       COALESCE(f.failed_count, 0) AS failed_payments,
       COALESCE(t.ticket_count, 0) AS support_tickets,
       ROUND(0.5 * LEAST(COALESCE(r.days_since_last_activity, 365) / 365.0, 1)
           + 0.3 * COALESCE(f.failed_count, 0) / 5.0
           + 0.2 * LEAST(COALESCE(t.ticket_count, 0) / 10.0, 1), 3) AS risk_score,
       ROUND(a.monthly_price * (0.5 * LEAST(COALESCE(r.days_since_last_activity, 365) / 365.0, 1)
           + 0.3 * COALESCE(f.failed_count, 0) / 5.0
           + 0.2 * LEAST(COALESCE(t.ticket_count, 0) / 10.0, 1)), 2) AS at_risk_revenue
FROM active a
LEFT JOIN recency r ON r.customer_id = a.customer_id
LEFT JOIN failed f ON f.customer_id = a.customer_id
LEFT JOIN tickets t ON t.customer_id = a.customer_id
ORDER BY at_risk_revenue DESC
LIMIT 50;

-- 32. Top 5 complaints per country, most recent completed quarter.
WITH recent_q AS (
    SELECT DATE_TRUNC('quarter', MAX(ticket_date))::date - INTERVAL '3 months' AS q_start
    FROM support_tickets
),
base AS (
    SELECT c.country,
           t.issue_subcategory,
           AVG(t.resolution_time_hours) AS avg_res_time,
           AVG(t.customer_satisfaction_score) AS avg_csat,
           COUNT(*) AS volume,
           ROW_NUMBER() OVER (PARTITION BY c.country ORDER BY COUNT(*) DESC) AS rn
    FROM support_tickets t
    JOIN customers c ON c.customer_id = t.customer_id
    CROSS JOIN recent_q rq
    WHERE t.ticket_date >= rq.q_start
      AND t.ticket_date < rq.q_start + INTERVAL '3 months'
    GROUP BY c.country, t.issue_subcategory
)
SELECT country,
       issue_subcategory,
       volume,
       ROUND(avg_res_time, 2) AS avg_resolution_hours,
       ROUND(avg_csat, 2) AS avg_satisfaction
FROM base
WHERE rn <= 5
ORDER BY country, volume DESC;

-- 33. Win-back candidates: churned customers with top-quartile CLV.
WITH spend AS (
    SELECT customer_id,
           SUM(amount) AS clv
    FROM payments
    WHERE payment_status = 'Success'
    GROUP BY customer_id
)
SELECT cl.customer_id,
       cl.churn_reason,
       s.clv,
       va.last_engagement
FROM churn_labels cl
JOIN spend s ON s.customer_id = cl.customer_id
LEFT JOIN (SELECT customer_id, MAX(viewing_date) AS last_engagement
           FROM viewing_activity GROUP BY customer_id) va ON va.customer_id = cl.customer_id
WHERE cl.churned
  AND s.clv >= (SELECT PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY clv) FROM spend)
ORDER BY s.clv DESC;

-- 34. Plan-migration analysis: most common paths + upgrader vs downgrader churn.
WITH mig AS (
    SELECT customer_id,
           plan_id,
           LAG(plan_id) OVER (PARTITION BY customer_id
                              ORDER BY subscription_start_date) AS prev_plan
    FROM subscriptions
),
paths AS (
    SELECT customer_id,
           prev_plan,
           plan_id AS new_plan,
           CASE WHEN prev_plan < plan_id THEN 'Upgrade' ELSE 'Downgrade' END AS direction
    FROM mig
    WHERE prev_plan IS NOT NULL AND prev_plan <> plan_id
)
SELECT prev_plan,
       new_plan,
       direction,
       COUNT(DISTINCT p.customer_id) AS customers,
       ROUND(100.0 * COUNT(DISTINCT CASE WHEN cl.churned THEN p.customer_id END)
             / COUNT(DISTINCT p.customer_id), 2) AS churn_rate_pct
FROM paths p
LEFT JOIN churn_labels cl ON cl.customer_id = p.customer_id
GROUP BY prev_plan, new_plan, direction
ORDER BY customers DESC;

-- 35. WAU / MAU trend over last 6 months + stickiness ratio.
WITH weeks AS (
    SELECT customer_id,
           DATE_TRUNC('week', viewing_date)::date AS week
    FROM viewing_activity
    WHERE viewing_date >= DATE_TRUNC('month', CURRENT_DATE) - INTERVAL '6 months'
    GROUP BY 1, 2
),
months AS (
    SELECT customer_id,
           DATE_TRUNC('month', viewing_date)::date AS month
    FROM viewing_activity
    WHERE viewing_date >= DATE_TRUNC('month', CURRENT_DATE) - INTERVAL '6 months'
    GROUP BY 1, 2
),
w AS (SELECT week, COUNT(*) AS wau FROM weeks GROUP BY week),
m AS (SELECT month, COUNT(*) AS mau FROM months GROUP BY month)
SELECT w.week,
       w.wau,
       m.mau,
       ROUND(100.0 * w.wau / m.mau, 2) AS stickiness_pct
FROM w
JOIN m ON DATE_TRUNC('month', w.week) = m.month
ORDER BY w.week;

-- 36. Negative feedback within 14 days of a failed payment or a CSAT<=2 ticket.
WITH neg_fb AS (
    SELECT customer_id, feedback_date, rating, feedback_text
    FROM customer_feedback
    WHERE rating <= 2
),
failed AS (
    SELECT customer_id, payment_date FROM payments WHERE payment_status = 'Failed'
),
bad_tickets AS (
    SELECT customer_id, ticket_date
    FROM support_tickets
    WHERE customer_satisfaction_score <= 2
)
SELECT DISTINCT nf.customer_id,
       nf.feedback_date,
       nf.rating,
       nf.feedback_text
FROM neg_fb nf
WHERE EXISTS (SELECT 1 FROM failed f
              WHERE f.customer_id = nf.customer_id
                AND ABS(f.payment_date - nf.feedback_date) <= 14)
   OR EXISTS (SELECT 1 FROM bad_tickets bt
              WHERE bt.customer_id = nf.customer_id
                AND ABS(bt.ticket_date - nf.feedback_date) <= 14);

-- 37. Full customer health score (0-100), ranked descending by risk.
WITH recency AS (
    SELECT customer_id,
           COALESCE((CURRENT_DATE - MAX(viewing_date)), 365) AS days_since
    FROM viewing_activity
    GROUP BY customer_id
),
pay AS (
    SELECT customer_id,
           COUNT(*) FILTER (WHERE payment_status = 'Failed') AS failed_count,
           COUNT(*) AS total_count
    FROM payments
    GROUP BY customer_id
),
sat AS (
    SELECT customer_id, AVG(customer_satisfaction_score) AS avg_csat
    FROM support_tickets
    WHERE customer_satisfaction_score IS NOT NULL
    GROUP BY customer_id
),
tenure AS (
    SELECT customer_id, (CURRENT_DATE - registration_date) AS tenure_days
    FROM customers
),
active AS (
    SELECT customer_id, plan_id FROM subscriptions WHERE subscription_status = 'Active'
)
SELECT a.customer_id,
       a.plan_id,
       COALESCE(r.days_since, 365) AS days_since_last_activity,
       COALESCE(p.failed_count, 0) AS failed_payments,
       ROUND(COALESCE(p.failed_count, 0) / NULLIF(p.total_count, 0), 3) AS failed_payment_rate,
       ROUND(COALESCE(s.avg_csat, 3), 2) AS avg_satisfaction,
       COALESCE(t.tenure_days, 0) AS tenure_days,
       ROUND(GREATEST(0, LEAST(100,
           100 * (1 - LEAST(COALESCE(r.days_since, 365) / 180.0, 1))   -- recency component
         - 40 * LEAST(COALESCE(p.failed_count, 0) / 5.0, 1)            -- payment-failure penalty
         + 10 * ((COALESCE(s.avg_csat, 3) - 1) / 4)                    -- satisfaction component
         + 15 * LEAST(COALESCE(t.tenure_days, 0) / 1095.0, 1)          -- tenure component
       )), 2) AS health_score
FROM active a
LEFT JOIN recency r ON r.customer_id = a.customer_id
LEFT JOIN pay p ON p.customer_id = a.customer_id
LEFT JOIN sat s ON s.customer_id = a.customer_id
LEFT JOIN tenure t ON t.customer_id = a.customer_id
ORDER BY health_score ASC;
