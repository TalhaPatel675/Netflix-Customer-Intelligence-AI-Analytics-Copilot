-- 01. How many active customers does the platform currently have, by country?
SELECT c.country,
       COUNT(DISTINCT s.customer_id) AS active_customers
FROM customers c
JOIN subscriptions s ON s.customer_id = c.customer_id
WHERE s.subscription_status = 'Active'
GROUP BY c.country
ORDER BY active_customers DESC;

-- 02. What is the total and average monthly revenue generated by each plan?
SELECT p.plan_name,
       SUM(s.monthly_price) AS total_monthly_revenue,
       AVG(s.monthly_price) AS avg_monthly_revenue
FROM subscriptions s
JOIN subscription_plans p ON p.plan_id = s.plan_id
WHERE s.subscription_status = 'Active'
GROUP BY p.plan_name
ORDER BY total_monthly_revenue DESC;

-- 03. What is the overall churn rate (percentage of customers with churned=true)?
SELECT ROUND(100.0 * SUM(churned::int) / COUNT(*), 2) AS churn_rate_pct
FROM churn_labels;

-- 04. Which acquisition channel brought in the most customers, and the churn rate per channel?
SELECT c.acquisition_channel,
       COUNT(DISTINCT c.customer_id) AS customers,
       ROUND(100.0 * SUM(cl.churned::int) / COUNT(*), 2) AS churn_rate_pct
FROM customers c
LEFT JOIN churn_labels cl ON cl.customer_id = c.customer_id
GROUP BY c.acquisition_channel
ORDER BY customers DESC;

-- 05. What is the average customer age by subscription plan?
SELECT p.plan_name,
       ROUND(AVG(c.age), 1) AS avg_age
FROM customers c
JOIN subscriptions s ON s.customer_id = c.customer_id
JOIN subscription_plans p ON p.plan_id = s.plan_id
WHERE s.subscription_status = 'Active'
GROUP BY p.plan_name
ORDER BY avg_age;

-- 06. List the top 10 most-watched titles by total watch_duration_minutes.
SELECT ct.title,
       SUM(va.watch_duration_minutes) AS total_watch_minutes
FROM viewing_activity va
JOIN content ct ON ct.content_id = va.content_id
GROUP BY ct.title
ORDER BY total_watch_minutes DESC
LIMIT 10;

-- 07. What is the average completion_percentage by content_type and genre?
