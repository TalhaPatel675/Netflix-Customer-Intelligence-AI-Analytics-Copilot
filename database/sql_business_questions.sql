-- 23. Customers whose watch time declined for three consecutive months.
WITH monthly AS (
    SELECT customer_id,
           DATE_TRUNC('month', viewing_date)::date AS month,
           SUM(watch_duration_minutes) AS m
    FROM viewing_activity
    GROUP BY 1, 2
),
lagged AS (
    SELECT *,
           LAG(m) OVER (PARTITION BY customer_id ORDER BY month) AS m1,
           LAG(m, 2) OVER (PARTITION BY customer_id ORDER BY month) AS m2
    FROM monthly
)
SELECT DISTINCT customer_id
FROM lagged
WHERE m < m1 AND m1 < m2;

-- 24. Monthly churn rate over the last 12 months.
WITH months AS (
    SELECT generate_series(DATE_TRUNC('month', CURRENT_DATE) - INTERVAL '11 months',
                           DATE_TRUNC('month', CURRENT_DATE), '1 month')::date AS month
),
churned AS (
    SELECT DATE_TRUNC('month', churn_date)::date AS month,
           COUNT(*) AS churned_count
    FROM churn_labels
    WHERE churn_date IS NOT NULL
    GROUP BY 1
),
active_at_start AS (
    SELECT DATE_TRUNC('month', subscription_start_date)::date AS month,
           COUNT(DISTINCT customer_id) AS active_count
    FROM subscriptions
    WHERE subscription_start_date < DATE_TRUNC('month', CURRENT_DATE)
    GROUP BY 1
)
SELECT m.month,
       COALESCE(ch.churned_count, 0) AS churned,
       COALESCE(a.active_count, 0) AS active_at_start,
       ROUND(100.0 * COALESCE(ch.churned_count, 0) / NULLIF(a.active_count, 0), 2) AS churn_rate_pct
FROM months m
LEFT JOIN churned ch ON ch.month = m.month
LEFT JOIN active_at_start a ON a.month = m.month
ORDER BY m.month;

-- 25. Customer retention rate by acquisition_channel.
SELECT c.acquisition_channel,
       COUNT(DISTINCT c.customer_id) AS acquired,
       COUNT(DISTINCT CASE WHEN s.subscription_status = 'Active' THEN c.customer_id END) AS still_active,
       ROUND(100.0 * COUNT(DISTINCT CASE WHEN s.subscription_status = 'Active' THEN c.customer_id END)
             / COUNT(DISTINCT c.customer_id), 2) AS retention_pct
FROM customers c
LEFT JOIN subscriptions s ON s.customer_id = c.customer_id
GROUP BY c.acquisition_channel
ORDER BY retention_pct DESC;

